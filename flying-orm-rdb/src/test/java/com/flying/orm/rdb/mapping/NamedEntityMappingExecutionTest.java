    @TestFactory
    Stream<DynamicTest> oneEnumUsesDifferentFieldRepresentationsThroughBothExecutionPaths() {
        return Stream.of(false, true).map(reactive -> DynamicTest.dynamicTest("reactive=" + reactive, () -> {
            String database = "named_entity_mapping_" + reactive;
            JdbcDataSource source = new JdbcDataSource();
            source.setURL("jdbc:h2:mem:" + database + ";DATABASE_TO_LOWER=TRUE");
            source.setUser("sa");
            source.setPassword("");
            ConnectionFactory factory = ConnectionFactories.get(ConnectionFactoryOptions.builder()
                    .option(DRIVER, "h2").option(PROTOCOL, H2ConnectionFactoryProvider.PROTOCOL_MEM)
                    .option(DATABASE, database).option(USER, "sa").option(PASSWORD, "")
                    .option(H2ConnectionFactoryProvider.OPTIONS, "DATABASE_TO_LOWER=TRUE").build());
            EntitySchemaDescriptor<Account> schema = EntitySchemaDescriptor.builder(Account.class)
                    .typeMappings(NamedEntityTypeMappingTest.namedBuilder()
                            .registerNamed("note-prefix", String.class, DatabaseType.of("VARCHAR"), prefix("N:"))
                            .registerNamed("value-prefix", String.class, DatabaseType.of("VARCHAR"), prefix("V:"))
                            .build()).build();
            assertEquals(List.of("BIGINT", "state-code", "state-number", "VARCHAR", "note-prefix", "value-prefix"),
                    schema.table().columns().stream().map(column -> column.codecId()).toList());
            assertEquals(DatabaseType.of("INTEGER"), schema.metadata().field("numeric").databaseType());
            try (Connection keeper = source.getConnection();
                 Statement statement = keeper.createStatement();
                 FlyingOrmClients clients = FlyingOrmClients.builder(ConnectionAccessTestSupport.jdbc(source),
                         ConnectionAccessTestSupport.reactive(factory)).configuredDialect("h2")
                         .entitySchema(schema).build()) {
                statement.execute("create table named_accounts(id bigint primary key, coded varchar, numeric integer, "
                        + "plain varchar, note varchar, represented varchar)");
                Account original = new Account(1L, State.DISABLED, State.DISABLED, State.DISABLED, "memo", StoredState.DISABLED);
                if (reactive) {
                    assertEquals(1L, clients.repository(Account.class).insert(original).block());
                    assertEquals(original, clients.repository(Account.class).findById(1L).block());
                } else {
                    assertEquals(1L, clients.syncRepository(Account.class).insert(original));
                    assertEquals(original, clients.syncRepository(Account.class).findById(1L));
                }
                DynamicRow aliased = reactive
                        ? clients.operator().dml().query(schema.form()).select(ValueExpression.field("note"), "note_alias")
                                .select(ValueExpression.field("numeric"), "state_alias").first().block()
                        : clients.syncOperator().dml().query(schema.form()).select(ValueExpression.field("note"), "note_alias")
                                .select(ValueExpression.field("numeric"), "state_alias").first();
                assertNotNull(aliased);
                assertEquals("memo", aliased.get("note_alias"));
                assertEquals(State.DISABLED, aliased.get("state_alias"));
                com.flying.orm.core.join.JoinQuerySpec.Builder joined = com.flying.orm.core.join.JoinQuerySpec.builder(schema.form());
                com.flying.orm.core.join.JoinQuerySpec joinSpec = joined
                        .select(ValueExpression.field(joined.root().field("note")), "note_alias")
                        .select(ValueExpression.field(joined.root().field("numeric")), "state_alias")
                        .select(ValueExpression.value(1).add(ValueExpression.value(2)), "calculated").build();
                List<DynamicRow> joinedRows = reactive ? clients.forms().selectJoin(joinSpec).collectList().block()
                        : clients.syncForms().selectJoin(joinSpec);
                assertNotNull(joinedRows);
                assertEquals("memo", joinedRows.getFirst().get("note_alias"));
                assertEquals(State.DISABLED, joinedRows.getFirst().get("state_alias"));
                assertEquals(3, ((Number) joinedRows.getFirst().get("calculated")).intValue());
                NoteProjection entityProjection = reactive
                        ? clients.repository(Account.class).createQuery()
                                .selectExpression(e -> e.field(Account::note), "note_alias")
                                .selectExpression(e -> e.field(Account::numeric), "state_alias")
                                .one(NoteProjection.class).block()
                        : clients.syncRepository(Account.class).createQuery()
                                .selectExpression(e -> e.field(Account::note), "note_alias")
                                .selectExpression(e -> e.field(Account::numeric), "state_alias")
                                .one(NoteProjection.class);
                assertEquals(new NoteProjection("memo", State.DISABLED), entityProjection);
                List<DynamicRow> aliasPage = reactive
                        ? clients.operator().dml().query(schema.form()).select(ValueExpression.field("note"), "note_alias")
                                .orderByAsc("id").page(1, 1).block().rows()
                        : clients.syncOperator().dml().query(schema.form()).select(ValueExpression.field("note"), "note_alias")
                                .orderByAsc("id").page(1, 1).rows();
                assertEquals("memo", aliasPage.getFirst().get("note_alias"));
                QuerySpec lock = QuerySpec.of(schema.form(), ConditionGroup.and().build())
                        .withExpression("note_alias", ValueExpression.field("note"))
                        .withExpression("state_alias", ValueExpression.field("numeric")).withLock(ReadLock.update());
                List<DynamicRow> locked = reactive ? clients.forms().lockingRead(lock).collectList().block()
                        : clients.syncForms().lockingRead(lock);
                assertNotNull(locked);
                assertEquals("memo", locked.getFirst().get("note_alias"));
                assertEquals(State.DISABLED, locked.getFirst().get("state_alias"));
                QuerySpec cursorSpec = QuerySpec.of(schema.form(), ConditionGroup.and().build())
                        .withProjection(List.of("id"), List.of())
                        .withExpression("note_alias", ValueExpression.field("note"))
                        .withExpression("state_alias", ValueExpression.field("numeric"));
                com.flying.orm.core.page.KeysetPageQuery cursor = com.flying.orm.core.page.KeysetPageQuery.first(
                        1, com.flying.orm.core.page.KeysetSort.asc("id", com.flying.orm.core.page.NullOrder.LAST));
                List<DynamicRow> cursorRows = reactive
                        ? clients.forms().keysetPage(cursorSpec, cursor).block().rows()
                        : clients.syncForms().keysetPage(cursorSpec, cursor).rows();
                assertEquals("memo", cursorRows.getFirst().get("note_alias"));
                assertEquals(State.DISABLED, cursorRows.getFirst().get("state_alias"));
                statement.execute("insert into named_accounts select 2,coded,numeric,plain,'N:next',represented "
                        + "from named_accounts where id=1");
                com.flying.orm.core.page.KeysetSort sort = com.flying.orm.core.page.KeysetSort.asc(
                        "note", com.flying.orm.core.page.NullOrder.LAST);
                com.flying.orm.core.page.KeysetPageQuery keyset = com.flying.orm.core.page.KeysetPageQuery.first(1, sort);
                QuerySpec hiddenSpec = cursorSpec.withProjection(List.of("note_alias", "state_alias"), List.of());
                com.flying.orm.core.page.KeysetPageResult<DynamicRow> first = reactive
                        ? clients.forms().keysetPage(hiddenSpec, keyset).block()
                        : clients.syncForms().keysetPage(hiddenSpec, keyset);
                assertNotNull(first);
                assertEquals(List.of("memo", 1L), first.nextPosition().values(), "hidden cursor uses the field codec");
                assertEquals(2, first.rows().getFirst().columnCount());
                assertEquals("memo", first.rows().getFirst().get("note_alias"));
                assertEquals(State.DISABLED, first.rows().getFirst().get("state_alias"));
                com.flying.orm.core.page.KeysetPageQuery after = com.flying.orm.core.page.KeysetPageQuery.after(
                        1, first.nextPosition(), sort);
                com.flying.orm.core.page.KeysetPageResult<DynamicRow> next = reactive
                        ? clients.forms().keysetPage(hiddenSpec, after).block()
                        : clients.syncForms().keysetPage(hiddenSpec, after);
                assertNotNull(next);
                assertEquals("next", next.rows().getFirst().get("note_alias"));
                assertEquals(State.DISABLED, next.rows().getFirst().get("state_alias"));
                assertFalse(next.hasMore());
                statement.execute("delete from named_accounts where id=2");
                try (ResultSet row = statement.executeQuery("select coded,numeric,plain,note,represented from named_accounts")) {
                    assertTrue(row.next());
                    assertEquals("D", row.getString(1));
                    assertEquals(0, row.getInt(2));
                    assertEquals("DISABLED", row.getString(3));
                    assertEquals("N:memo", row.getString(4));
                    assertEquals("V:D", row.getString(5));
                    assertFalse(row.next());
                }
                if (reactive) verifyReactive(clients.repository(Account.class));
                else verifySync(clients.syncRepository(Account.class));
                try (ResultSet row = statement.executeQuery("select count(*) from named_accounts")) {
                    assertTrue(row.next());
                    assertEquals(0L, row.getLong(1));
                }
            }
        }));
    }

    public record NoteProjection(String note_alias, State state_alias) { }

    private static void verifySync(SyncFormRepository<Account> repository) {
        assertEquals(1L, repository.createUpdate().setExpression(Account::note,
                e -> e.value(Account::note, "expression").coalesce(e.field(Account::note)))
                .setExpression(Account::numeric, e -> e.value(Account::numeric, State.ACTIVE)
                        .coalesce(e.field(Account::numeric))).where(Account::id, 1L).execute());
        assertEquals("expression", repository.findById(1L).note());
        assertEquals(State.ACTIVE, repository.findById(1L).numeric());
        assertEquals(1L, repository.createUpdate().set(Account::coded, State.ACTIVE)
                .set(Account::numeric, State.ACTIVE).set(Account::note, "changed")
                .set(Account::represented, StoredState.ACTIVE).where(Account::plain, State.DISABLED).execute());
        Account expected = new Account(1L, State.ACTIVE, State.ACTIVE, State.DISABLED, "changed", StoredState.ACTIVE);
        assertEquals(expected, repository.createQuery().where(Account::coded, State.ACTIVE)
                .where(Account::note, "changed").where(Account::represented, StoredState.ACTIVE)
                .in(Account::numeric, List.of(State.ACTIVE)).one());
        assertEquals(List.of(expected), repository.createQuery().where(Account::numeric, State.ACTIVE)
                .orderByAsc(Account::id).page(1, 10).rows());
        assertEquals(1L, repository.createDelete().where(Account::coded, State.ACTIVE)
                .where(Account::numeric, State.ACTIVE).execute());
    }

    private static void verifyReactive(ReactiveFormRepository<Account> repository) {
        assertEquals(1L, repository.createUpdate().setExpression(Account::note,
                e -> e.value(Account::note, "expression").coalesce(e.field(Account::note)))
                .setExpression(Account::numeric, e -> e.value(Account::numeric, State.ACTIVE)
                        .coalesce(e.field(Account::numeric))).where(Account::id, 1L).execute().block());
        assertEquals("expression", repository.findById(1L).block().note());
        assertEquals(State.ACTIVE, repository.findById(1L).block().numeric());
        assertEquals(1L, repository.createUpdate().set(Account::coded, State.ACTIVE)
                .set(Account::numeric, State.ACTIVE).set(Account::note, "changed")
                .set(Account::represented, StoredState.ACTIVE).where(Account::plain, State.DISABLED).execute().block());
        Account expected = new Account(1L, State.ACTIVE, State.ACTIVE, State.DISABLED, "changed", StoredState.ACTIVE);
        assertEquals(expected, repository.createQuery().where(Account::coded, State.ACTIVE)
                .where(Account::note, "changed").where(Account::represented, StoredState.ACTIVE)
                .in(Account::numeric, List.of(State.ACTIVE)).one().block());
        assertEquals(List.of(expected), repository.createQuery().where(Account::numeric, State.ACTIVE)
                .orderByAsc(Account::id).page(1, 10).block().rows());
        assertEquals(1L, repository.createDelete().where(Account::coded, State.ACTIVE)
                .where(Account::numeric, State.ACTIVE).execute().block());
    }

    @TableName("named_accounts")
    private record Account(@TableId Long id,
                           @TableColumn(databaseTypeId = "state-code") State coded,
                           @TableColumn(databaseTypeId = "state-number") State numeric,
                           State plain,
                           @TableColumn(databaseTypeId = "note-prefix") String note,
                           @TableColumn(databaseTypeId = "value-prefix") StoredState represented) {
    }

    private enum StoredState {
        ACTIVE("A"), DISABLED("D");
        @EnumValue
        private final String code;
        StoredState(String code) { this.code = code; }
    }

    private static ValueCodec prefix(String prefix) {
        return new ValueCodec() {
            @Override
            public boolean supports(Class<?> type) { return type == String.class; }
            @Override
            public Object write(Object value) { return value == null ? null : prefix + value; }
            @Override
            public Object read(Object value, Class<?> type) {
                if (value == null) return null;
                String text = (String) value;
                if (!text.startsWith(prefix)) throw new IllegalArgumentException("wrong field representation");
                return text.substring(prefix.length());
            }
        };
    }
