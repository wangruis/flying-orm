    @TestFactory
    Stream<DynamicTest> nonKeyIdentityKeepsDatabaseDefaultsForInsertAndConflictUpdate() {
        return Stream.of(false, true).map(reactive -> DynamicTest.dynamicTest("reactive=" + reactive, () -> {
            String database = "upsert_generated_column_" + reactive;
            JdbcDataSource source = new JdbcDataSource();
            source.setURL("jdbc:h2:mem:" + database + ";DATABASE_TO_LOWER=TRUE");
            source.setUser("sa");
            source.setPassword("");
            ConnectionFactory factory = ConnectionFactories.get(ConnectionFactoryOptions.builder()
                    .option(DRIVER, "h2").option(PROTOCOL, H2ConnectionFactoryProvider.PROTOCOL_MEM)
                    .option(DATABASE, database).option(USER, "sa").option(PASSWORD, "")
                    .option(H2ConnectionFactoryProvider.OPTIONS, "DATABASE_TO_LOWER=TRUE").build());
            EntitySchemaDescriptor<GeneratedColumn> schema = EntitySchemaDescriptor.builder(GeneratedColumn.class).build();
            try (Connection keeper = source.getConnection(); Statement statement = keeper.createStatement();
                 FlyingOrmClients clients = FlyingOrmClients.builder(ConnectionAccessTestSupport.jdbc(source),
                         ConnectionAccessTestSupport.reactive(factory)).configuredDialect("h2").entitySchema(schema).build()) {
                statement.execute("create table generated_columns(id bigint primary key, "
                        + "serial bigint generated by default as identity, name varchar)");
                GeneratedColumn first = new GeneratedColumn(1L, null, "first");
                if (reactive) clients.repository(GeneratedColumn.class).insert(first).block();
                else clients.syncRepository(GeneratedColumn.class).insert(first);
                long original;
                try (ResultSet row = statement.executeQuery("select serial from generated_columns where id=1")) {
                    assertTrue(row.next());
                    original = row.getLong(1);
                }
                List<GeneratedColumn> entities = List.of(new GeneratedColumn(1L, 999L, "changed"),
                        new GeneratedColumn(2L, 999L, "new"));
                if (reactive) clients.repository(GeneratedColumn.class).upsertBatch(entities).block();
                else clients.syncRepository(GeneratedColumn.class).upsertBatch(entities);
                try (ResultSet rows = statement.executeQuery("select id,serial,name from generated_columns order by id")) {
                    assertTrue(rows.next());
                    assertEquals(1L, rows.getLong(1));
                    assertEquals(original, rows.getLong(2));
                    assertEquals("changed", rows.getString(3));
                    assertTrue(rows.next());
                    assertEquals(2L, rows.getLong(1));
                    assertNotEquals(999L, rows.getLong(2));
                    assertNotEquals(original, rows.getLong(2));
                    assertFalse(rows.wasNull());
                    assertEquals("new", rows.getString(3));
                    assertFalse(rows.next());
                }
                assertEquals(999L, entities.getLast().serial(), "non-key generated values are not implicitly assigned");
                statement.execute("create table business_accounts(id bigint generated by default as identity primary key, "
                        + "mail_address varchar unique, name varchar)");
                BusinessAccount account = new BusinessAccount("a@test", "original");
                if (reactive) clients.repository(BusinessAccount.class).upsert(account, "emailAddress").block();
                else clients.syncRepository(BusinessAccount.class).upsert(account, "emailAddress");
                assertNull(account.id);
                long id;
                try (ResultSet row = statement.executeQuery("select id from business_accounts")) {
                    assertTrue(row.next());
                    id = row.getLong(1);
                    assertFalse(row.wasNull());
                }
                List<BusinessAccount> accounts = List.of(new BusinessAccount("a@test", "changed"),
                        new BusinessAccount("b@test", "new"));
                if (reactive) clients.repository(BusinessAccount.class).upsertBatch(accounts, "emailAddress").block();
                else clients.syncRepository(BusinessAccount.class).upsertBatch(accounts, "emailAddress");
                try (ResultSet rows = statement.executeQuery("select id,name from business_accounts order by mail_address")) {
                    assertTrue(rows.next());
                    assertEquals(id, rows.getLong(1));
                    assertEquals("changed", rows.getString(2));
                    assertTrue(rows.next());
                    assertNotEquals(id, rows.getLong(1));
                    assertFalse(rows.wasNull());
                    assertEquals("new", rows.getString(2));
                    assertFalse(rows.next());
                }
                assertTrue(accounts.stream().allMatch(entity -> entity.id == null));
            }
        }));
    }

