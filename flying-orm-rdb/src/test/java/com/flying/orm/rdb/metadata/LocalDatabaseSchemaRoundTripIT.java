    @Test
    void oracleEntityAnnotationsRoundTripExactly() throws Exception {
        Properties configuration = configuration();
        String url = required(configuration, "oracle.url");
        String administrator = required(configuration, "oracle.user");
        String administratorPassword = required(configuration, "oracle.password");
        String schemaPassword = required(configuration, "oracle.schemaPassword");
        String schema = "FO32_" + UUID.randomUUID().toString().replace("-", "").substring(0, 20);
        try (Connection connection = DriverManager.getConnection(url, administrator, administratorPassword)) {
            execute(connection, "create user " + schema + " identified by \"" + schemaPassword + "\"");
            execute(connection, "grant create session, create table, create sequence to " + schema);
            execute(connection, "alter user " + schema + " quota unlimited on users");
        }
        try {
            certifyCurrentNamespace(RdbDialect.oracle(), new ScopedDataSource(
                    url, schema, schemaPassword, null));
        } finally {
            try (Connection connection = DriverManager.getConnection(url, administrator, administratorPassword)) {
                execute(connection, "drop user " + schema + " cascade");
            }
        }
    }

