    @Test
    void postgresqlRejectsDatabaseFactsOutsideTheClosedEntityModel() throws Exception {
        Properties configuration = configuration();
        String url = required(configuration, "postgresql.url");
        String user = required(configuration, "postgresql.user");
        String password = required(configuration, "postgresql.password");
        String namespace = "flying_orm_32_guard_" + UUID.randomUUID().toString().replace("-", "");
        boolean created = false;
        try (Connection administration = DriverManager.getConnection(url, user, password)) {
            execute(administration, Database.POSTGRESQL.createNamespace(namespace));
            created = true;
            DataSource scoped = new ScopedDataSource(
                    url, user, password, Database.POSTGRESQL.enterNamespace(namespace));
            try (Connection connection = scoped.getConnection()) {
                execute(connection, "create table fo32_rt_bad_default (value text default ('x'::text || 'y'::text))");
                execute(connection, "create table fo32_rt_bad_sequence "
                        + "(id bigint generated by default as identity (maxvalue 10))");
                execute(connection, "create table fo32_rt_bad_unique "
                        + "(code varchar(32), payload varchar(32), "
                        + "constraint uk_fo32_rt_bad_unique unique (code) include (payload))");
            }
            JdbcSqlExecutor executor = JdbcSqlExecutor.create(scoped, RdbDialect.postgresql());
            JdbcFormMetadataReader reader = JdbcFormMetadataReaders.create(executor, RdbDialect.postgresql());

            assertThrows(IllegalStateException.class, () -> reader.readSnapshot("fo32_rt_bad_default"));
            assertThrows(IllegalStateException.class, () -> reader.readSnapshot("fo32_rt_bad_sequence"));
            assertThrows(IllegalStateException.class, () -> reader.readSnapshot("fo32_rt_bad_unique"));
        } finally {
            if (created) {
                try (Connection administration = DriverManager.getConnection(url, user, password)) {
                    execute(administration, Database.POSTGRESQL.dropNamespace(namespace));
                }
            }
        }
    }

