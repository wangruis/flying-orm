    private static void certify(Database database, RdbDialect dialect) throws Exception {
        Properties configuration = configuration();
        String prefix = database.key + ".";
        certify(database, dialect,
                required(configuration, prefix + "url"),
                required(configuration, prefix + "user"),
                required(configuration, prefix + "password"));
    }

    private static void certify(
            Database database,
            RdbDialect dialect,
            String url,
            String user,
            String password) throws Exception {
        String namespace = "flying_orm_32_rt_" + UUID.randomUUID().toString().replace("-", "");
        boolean created = false;
        try (Connection administration = DriverManager.getConnection(url, user, password)) {
            execute(administration, database.createNamespace(namespace));
            created = true;
            DataSource scoped = new ScopedDataSource(url, user, password, database.enterNamespace(namespace));
            certifyCurrentNamespace(dialect, scoped);
        } finally {
            if (created) {
                try (Connection administration = DriverManager.getConnection(url, user, password)) {
                    execute(administration, database.dropNamespace(namespace));
                }
            }
        }
    }

    private static void certifyCurrentNamespace(RdbDialect dialect, DataSource scoped) throws Exception {
        JdbcSqlExecutor executor = JdbcSqlExecutor.create(scoped, dialect);
        JdbcFormMetadataReader reader = JdbcFormMetadataReaders.create(executor, dialect);
        JdbcSchemaClient schemaClient = JdbcSchemaClient.create(executor, dialect);
        DatabaseDescriptor descriptor = descriptor(scoped, dialect);
        try (EntityModelRegistry models = EntityModelRegistry.create(CacheRegionPolicy.disabled())) {
            EntitySchemaSynchronizer synchronizer = new EntitySchemaSynchronizer(
                    models, null, null, schemaClient, reader);

            synchronizeAndValidate(
                    synchronizer, schemaClient, reader, descriptor, dialect,
                    List.of(RoundTripOrder.class, RoundTripCustomer.class, RoundTripEvolutionV1.class));
            synchronizeAndValidate(
                    synchronizer, schemaClient, reader, descriptor, dialect,
                    List.of(RoundTripEvolutionV2.class));

            List<RelationalTableDefinition> desired = List.of(
                    entityTable(RoundTripCustomer.class),
                    entityTable(RoundTripOrder.class),
                    entityTable(RoundTripEvolutionV2.class));
            assertTrue(reader.snapshotCoverage().isComplete());
            for (RelationalTableDefinition table : desired) {
                SchemaSnapshot actual = reader.readSnapshot(table.identity().table());
                assertTrue(actual.completeTable().isPresent(), table.identity().table());
                ReviewedSchemaPlan exact = schemaClient.reviewRelational(
                        descriptor, table, reader, SchemaCompatibilityMode.EXACT);
                assertTrue(exact.steps().isEmpty(), table.identity().table());
            }
        }
    }

    private static RelationalTableDefinition entityTable(Class<?> entityType) {
        return EntitySchemaDescriptor.builder(entityType).build().table();
    }

    private static DatabaseDescriptor descriptor(DataSource dataSource, RdbDialect dialect) throws SQLException {
        try (Connection connection = dataSource.getConnection()) {
            DatabaseMetaData metadata = connection.getMetaData();
            return DatabaseDescriptor.of(
                    metadata.getDatabaseProductName(), metadata.getDatabaseProductVersion(), dialect);
        }
    }

    private static void synchronizeAndValidate(
            EntitySchemaSynchronizer synchronizer,
            JdbcSchemaClient schemaClient,
            JdbcFormMetadataReader reader,
            DatabaseDescriptor database,
            RdbDialect dialect,
            List<Class<?>> entityTypes) {
        Map<String, SchemaMigrationApproval> approvals = new LinkedHashMap<>();
        List<String> reviewedSql = new ArrayList<>();
        for (Class<?> entityType : entityTypes) {
            RelationalTableDefinition desired = entityTable(entityType);
            ReviewedSchemaPlan plan = schemaClient.reviewRelational(
                    database, desired, reader, SchemaCompatibilityMode.EXACT);
            for (var step : plan.steps()) {
                if (!step.executable()) {
                    try {
                        RelationalSchemaSqlRenderer.create(dialect.schema()).render(step.operation());
                    } catch (UnsupportedOperationException unsupported) {
                        throw new AssertionError("manual schema step " + step.operation().kind() + "/"
                                + step.operation().objectName() + ": " + unsupported.getMessage(), unsupported);
                    }
                }
            }
            assertTrue(!plan.requiresManualAction(), () -> "manual schema steps: "
                    + plan.steps().stream()
                            .filter(step -> !step.executable())
                            .map(step -> step.operation().kind() + "/" + step.operation().objectName())
                            .toList());
            plan.steps().forEach(step -> step.request().ifPresent(
                    request -> reviewedSql.add(desired.identity().table() + ": " + request.sql())));
            approvals.put(desired.identity().table(),
                          SchemaMigrationApproval.approve(plan, "local real-database certification"));
        }
        EntityRelationalSchemaSyncReport updated = synchronizer.synchronizeRelational(
                database, EntitySchemaSyncMode.FULL_UPDATE, approvals, entityTypes);
        if (!updated.successful()) {
            for (Class<?> entityType : entityTypes) {
                reader.readSnapshot(entityTable(entityType).identity().table());
            }
        }
        assertTrue(updated.successful(), () -> executionEvidence(updated) + "; reviewedSql=" + reviewedSql);
        EntityRelationalSchemaSyncReport validated = synchronizer.synchronizeRelational(
                database, EntitySchemaSyncMode.VALIDATE, entityTypes);
        assertTrue(validated.successful(), () -> executionEvidence(validated));
    }

    private static String executionEvidence(EntityRelationalSchemaSyncReport report) {
        StringBuilder evidence = new StringBuilder("mode=").append(report.mode());
        for (int resultIndex = 0; resultIndex < report.results().size(); resultIndex++) {
            var result = report.results().get(resultIndex);
            evidence.append("; result[").append(resultIndex).append("]=").append(result.status());
            for (var step : result.steps()) {
                evidence.append(" step[").append(step.order()).append("]=").append(step.status());
                step.failureSummary().ifPresent(summary -> evidence.append('(').append(summary).append(')'));
            }
            result.verification().ifPresent(verification -> evidence.append(" verification=")
                    .append(verification.status()).append(':')
                    .append(verification.operations().stream()
                            .map(operation -> operation.kind() + "/" + operation.objectName())
                            .toList()));
        }
        return evidence.toString();
    }

    private static Properties configuration() throws IOException {
        Path path = Path.of(System.getProperty("flying.orm.it.config")).toAbsolutePath().normalize();
        Properties properties = new Properties();
        try (var input = Files.newInputStream(path)) {
            properties.load(input);
        }
        return properties;
    }

    private static String required(Properties properties, String key) {
        String value = properties.getProperty(key);
        if (value == null || value.isBlank()) {
            throw new IllegalStateException("missing real-database test property: " + key);
        }
        return value.trim();
    }

    private static void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private enum Database {
        POSTGRESQL("postgresql") {
            @Override
            String createNamespace(String name) {
                return "create schema \"" + name + "\"";
            }

            @Override
            String enterNamespace(String name) {
                return "set search_path to \"" + name + "\"";
            }

            @Override
            String dropNamespace(String name) {
                return "drop schema \"" + name + "\" cascade";
            }
        },
        MYSQL("mysql") {
            @Override
            String createNamespace(String name) {
                return "create database `" + name
                        + "` character set utf8mb4 collate utf8mb4_0900_ai_ci";
            }

            @Override
            String enterNamespace(String name) {
                return "use `" + name + "`";
            }

            @Override
            String dropNamespace(String name) {
                return "drop database `" + name + "`";
            }
        },
        H2("h2") {
            @Override
            String createNamespace(String name) {
                return "create schema " + name;
            }

            @Override
            String enterNamespace(String name) {
                return "set schema " + name;
            }

            @Override
            String dropNamespace(String name) {
                return "drop schema " + name + " cascade";
            }
        },
        SQL_SERVER("sqlserver") {
            @Override
            String createNamespace(String name) {
                return "create database [" + name + "]";
            }

            @Override
            String enterNamespace(String name) {
                return "use [" + name + "]";
            }

            @Override
            String dropNamespace(String name) {
                return "drop database [" + name + "]";
            }
        };

        private final String key;

        Database(String key) {
            this.key = key;
        }

        abstract String createNamespace(String name);

        abstract String enterNamespace(String name);

        abstract String dropNamespace(String name);
    }

    private static final class ScopedDataSource implements DataSource {

        private final String url;
        private final String user;
        private final String password;
        private final String setupSql;

        private ScopedDataSource(String url, String user, String password, String setupSql) {
            this.url = url;
            this.user = user;
            this.password = password;
            this.setupSql = setupSql;
        }

        @Override
        public Connection getConnection() throws SQLException {
            return initialize(DriverManager.getConnection(url, user, password));
        }

        @Override
        public Connection getConnection(String username, String suppliedPassword) throws SQLException {
            return initialize(DriverManager.getConnection(url, username, suppliedPassword));
        }

        private Connection initialize(Connection connection) throws SQLException {
            try {
                if (setupSql != null && !setupSql.isBlank()) {
                    execute(connection, setupSql);
                }
                return connection;
            } catch (SQLException error) {
                connection.close();
                throw error;
            }
        }

        @Override
        public PrintWriter getLogWriter() throws SQLException {
            return DriverManager.getLogWriter();
        }

        @Override
        public void setLogWriter(PrintWriter out) throws SQLException {
            DriverManager.setLogWriter(out);
        }

        @Override
        public void setLoginTimeout(int seconds) throws SQLException {
            DriverManager.setLoginTimeout(seconds);
        }

        @Override
        public int getLoginTimeout() throws SQLException {
            return DriverManager.getLoginTimeout();
        }

        @Override
        public Logger getParentLogger() throws SQLFeatureNotSupportedException {
            return Logger.getLogger("com.flying.orm.rdb.metadata.roundtrip");
        }

        @Override
        public <T> T unwrap(Class<T> iface) throws SQLException {
            if (iface.isInstance(this)) {
                return iface.cast(this);
            }
            throw new SQLException("data source wrapper does not expose the requested type");
        }

        @Override
        public boolean isWrapperFor(Class<?> iface) {
            return iface.isInstance(this);
        }
    }

